// Writes .dev/dev.patch.yml: the template's rows pointed at its local checkout's
// built host entries, this project's row pointed at lib/host.js, and the editor
// turned on, for
//
//   pnpm build                      (here, and `pnpm build` in the template checkout)
//   pnpm dev:patch
//   dsh --profile web --patch .dev/dev.patch.yml
//
// The checkout is package.json#dshEditor.checkout, or DSH_EDITOR_TEMPLATE.
// DSH resolves a local row by absolute file path (a directory fails to import).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'))
const template = resolve(root, process.env.DSH_EDITOR_TEMPLATE ?? manifest.dshEditor.checkout)
const posix = path => path.split('\\').join('/')

const entries = [
  ...['core', 'text', 'layout-main', 'context'].map(dir => [`dsh-editor-${dir}`, resolve(template, 'packages', dir, 'lib/host.js')]),
  ['dsh-document', resolve(root, 'lib/host.js')],
]
const missing = entries.filter(([, path]) => !existsSync(path)).map(([, path]) => path)
if (missing.length > 0) {
  console.error(`Not built yet (run \`pnpm build\` there):\n  ${missing.join('\n  ')}`)
  process.exit(1)
}

const patch = [
  '# Generated by scripts/dev-patch.mjs: local checkouts, editor on.',
  '- insert:',
  ...entries.flatMap(([id, path]) => [`    - id: ${id}`, `      name: '${posix(path)}'`]),
  '- id: dsh-editor-core',
  '  config:',
  '    enabled: true',
  '',
].join('\n')
mkdirSync(resolve(root, '.dev'), { recursive: true })
writeFileSync(resolve(root, '.dev/dev.patch.yml'), patch)
console.log(patch)
